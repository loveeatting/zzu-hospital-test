def topic_brief(t):
    return {
        "id": t["id"],
        "title": t["title"],
        "category": t["category"],
        "department": t["department"],
        "alert": t["alert"],
        "summary": t["symptoms"][0] if t["symptoms"] else "",
    }


def topic_detail(t):
    return {
        "id": t["id"],
        "title": t["title"],
        "category": t["category"],
        "department": t["department"],
        "alert": t["alert"],
        "symptoms": t["symptoms"],
        "prevention": t["prevention"],
        "care": t["care"],
        "see_doctor": t["see_doctor"],
    }


def _score(topic, q):
    if not q:
        return 0
    score = 0
    if q in topic["title"]:
        score += 5
    for kw in topic["keywords"]:
        # 关键词越长越具体，权重越高（例如「咳嗽两周」优先于「咳嗽」）
        if kw in q:
            score += 4 + len(kw)
        elif q in kw:
            score += 2
    if q in topic["category"]:
        score += 2
    for field in ("symptoms", "prevention", "care", "see_doctor"):
        for line in topic[field]:
            if q in line:
                score += 1
    return score


def search(q="", category="", limit=30):
    """按关键词/分类检索知识条目，返回简要列表。"""
    q = (q or "").strip()
    category = (category or "").strip()

    pool = TOPICS
    if category:
        pool = [t for t in pool if t["category"] == category]

    if q:
        scored = [(_score(t, q), t) for t in pool]
        scored = [(s, t) for s, t in scored if s > 0]
        scored.sort(key=lambda x: -x[0])
        pool = [t for _, t in scored]

    return [topic_brief(t) for t in pool[:limit]]


def get(topic_id):
    for t in TOPICS:
        if t["id"] == topic_id:
            return t
    return None


def categories():
    from collections import Counter
    c = Counter(t["category"] for t in TOPICS)
    return [{"name": name, "count": c[name]} for name in CATEGORIES if c[name]]
